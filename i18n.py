_ALL_TRANSLATIONS = {**ROOM_TRANSLATIONS, **NAME_TRANSLATIONS, **TEXT_TRANSLATIONS}
_SORTED_TRANSLATIONS = sorted(_ALL_TRANSLATIONS.items(), key=lambda item: len(item[0]), reverse=True)
_COMPILED_TRANSLATIONS = []
for _source, _target in _SORTED_TRANSLATIONS:
    if re.fullmatch(r"[A-Za-z]+", _source):
        _pattern = re.compile(rf"(?<![A-Za-z]){re.escape(_source)}(?![A-Za-z])")
    else:
        _pattern = re.compile(re.escape(_source))
    _COMPILED_TRANSLATIONS.append((_pattern, _target))
_REVERSE_NAMES = {value: key for key, value in NAME_TRANSLATIONS.items()}


def translate(value: Any) -> Any:
    if not isinstance(value, str):
        return value

    translated = value
    for pattern, target in _COMPILED_TRANSLATIONS:
        translated = pattern.sub(target, translated)
    return translated


def canonicalize_input(value: Any) -> Any:
    if not isinstance(value, str):
        return value

    normalized = value.strip()
    if normalized in _REVERSE_NAMES:
        return _REVERSE_NAMES[normalized]
    if normalized in {"保存", "保存游戏"}:
        return "Save"
    return value


_output_capture: list[str] | None = None


@contextmanager
def capture_output() -> Iterator[list[str]]:
    global _output_capture
    previous = _output_capture
    captured: list[str] = []
    _output_capture = captured
    try:
        yield captured
    finally:
        _output_capture = previous


def captured_text(lines: list[str], limit: int = 1200) -> str:
    text = "".join(lines)
    text = re.sub(r"\x1b\[[0-9;]*m", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text[:limit]


def ansiprint(*args: Any, **kwargs: Any) -> None:
    _ansiprint(*(translate(arg) for arg in args), **kwargs)


_original_print = builtins.print
_original_input = builtins.input
_installed = False


def _localized_print(*args: Any, **kwargs: Any) -> None:
    translated_args = tuple(translate(arg) for arg in args)
    if _output_capture is not None and kwargs.get("file") is None:
        separator = str(kwargs.get("sep", " "))
        ending = str(kwargs.get("end", "\n"))
        _output_capture.append(separator.join(str(arg) for arg in translated_args) + ending)
        return
    _original_print(*translated_args, **kwargs)


def _localized_input(prompt: str = "", *args: Any, **kwargs: Any) -> str:
    return canonicalize_input(_original_input(translate(prompt), *args, **kwargs))


def install() -> None:
    global _installed
    if _installed:
        return
    builtins.print = _localized_print
    builtins.input = _localized_input
    _installed = True


install()
